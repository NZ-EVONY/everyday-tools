// Regenerates tests/fixtures/unicode-names.json and data/unicode-blocks.json from the Unicode
// Character Database. Run it only when the style tables in src/assets/lib/fancy.js change.
//   node scripts/make-unicode-fixture.mjs <dir>
// <dir> holds UnicodeData.txt, Blocks.txt, NamesList.txt and DerivedAge.txt for one Unicode version, from
// https://www.unicode.org/Public/<version>/ucd/ (or the Unicode Consortium's mirror at
// https://raw.githubusercontent.com/unicode-org/unicodetools/main/unicodetools/data/ucd/<version>/).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { STYLES, FRAMES, MATH_GAPS } from "../src/assets/lib/fancy.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = process.argv[2];
if (!dir) { console.error("usage: node scripts/make-unicode-fixture.mjs <ucd-dir>"); process.exit(2); }
const read = f => fs.readFileSync(path.join(dir, f), "utf8");
const hex = n => n.toString(16).toUpperCase().padStart(4, "0");

const blocksTxt = read("Blocks.txt");
const version = (blocksTxt.match(/^# Blocks-(\d+\.\d+\.\d+)\.txt/m) || [])[1];
if (!version) throw new Error("Blocks.txt has no version header");

const names = new Map(), decomp = new Map();
for (const line of read("UnicodeData.txt").split("\n")) {
  if (!line) continue;
  const f = line.split(";");
  names.set(parseInt(f[0], 16), f[1]);
  if (f[5]) decomp.set(parseInt(f[0], 16), f[5]);
}

// Reserved slots in the math block and the character NamesList points each one to.
const reserved = {};
const nl = read("NamesList.txt").split("\n");
nl.forEach((line, i) => {
  const m = line.match(/^(1D[4-7][0-9A-F]{2})\t<reserved>/);
  if (!m) return;
  const x = (nl[i + 1] || "").match(/^\tx \(.* - ([0-9A-F]{4,5})\)/);
  reserved[m[1]] = x ? x[1] : null;
});
const mathNote = (nl[nl.findIndex(l => l.startsWith("@@\t1D400\t")) + 2] || "").replace(/^@\+\t+/, "");

// Every code point any style or frame can produce, the plain letters and digits, and the whole math block.
const want = new Set();
const add = s => { for (const ch of s) want.add(ch.codePointAt(0)); };
add("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789");
for (const s of STYLES) { if (s.map) for (const [k, v] of Object.entries(s.map)) { add(k); add(v); } if (s.mark) want.add(s.mark); }
for (const fr of FRAMES) add(fr.prefix + fr.suffix);
for (const g of Object.values(MATH_GAPS)) for (const c of Object.values(g)) want.add(c);
for (let c = 0x1D400; c <= 0x1D7FF; c++) want.add(c);

const out = { names: {}, decomposition: {} };
const missing = [];
for (const c of [...want].sort((a, b) => a - b)) {
  if (names.has(c)) { out.names[hex(c)] = names.get(c); if (decomp.has(c)) out.decomposition[hex(c)] = decomp.get(c); }
  else if (!(c >= 0x1D400 && c <= 0x1D7FF)) missing.push(hex(c));
}
if (missing.length) throw new Error(`Code points used by the tool but not assigned in Unicode ${version}: ${missing.join(" ")}`);

// The Unicode version that first encoded a few characters the guide mentions.
const AGE_OF = [0x1D400, 0x2102, 0x210E, 0x1D4C1, 0xA7AF, 0x107A5];
const ages = {};
for (const line of read("DerivedAge.txt").split("\n")) {
  const m = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([\d.]+)/);
  if (!m) continue;
  const a = parseInt(m[1], 16), b = parseInt(m[2] || m[1], 16);
  for (const c of AGE_OF) if (c >= a && c <= b) ages[`U+${hex(c)}`] = { name: names.get(c), version: m[3] };
}
if (Object.keys(ages).length !== AGE_OF.length) throw new Error("DerivedAge.txt is missing a code point");

const blocks = blocksTxt.split("\n").map(l => l.match(/^([0-9A-F]+)\.\.([0-9A-F]+); (.+)$/)).filter(Boolean)
  .map(m => ({ name: m[3].trim(), first: parseInt(m[1], 16), last: parseInt(m[2], 16) }));
const used = blocks.filter(b => [...want].some(c => c >= b.first && c <= b.last && (names.has(c))));

fs.writeFileSync(path.join(ROOT, "tests/fixtures/unicode-names.json"), JSON.stringify({
  _comment: `Generated by scripts/make-unicode-fixture.mjs from the Unicode Character Database ${version} (UnicodeData.txt, NamesList.txt). Names and compatibility decompositions of every code point the fancy text tool can output, the whole Mathematical Alphanumeric Symbols block, and NamesList's cross-reference for each reserved slot in that block. Do not edit by hand.`,
  unicodeVersion: version,
  mathBlockNote: mathNote,
  reservedInMathBlock: reserved,
  names: out.names,
  decomposition: out.decomposition,
}, null, 1) + "\n");

fs.writeFileSync(path.join(ROOT, "data/unicode-blocks.json"), JSON.stringify({
  _comment: `Unicode blocks the fancy text tool draws on, from Blocks.txt, and the version that first encoded a few characters, from DerivedAge.txt (Unicode ${version}). Generated by scripts/make-unicode-fixture.mjs.`,
  unicodeVersion: version,
  sourceId: "unicode-blocks",
  blocks: used.map(b => ({ name: b.name, first: `U+${hex(b.first)}`, last: `U+${hex(b.last)}` })),
  agesSourceId: "unicode-derived-age",
  ages,
}, null, 2) + "\n");

console.log(`Unicode ${version}: ${Object.keys(out.names).length} names, ${Object.keys(reserved).length} reserved math slots, ${used.length} blocks.`);
